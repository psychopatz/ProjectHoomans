"""Render deterministic dialogue Lua shards and translation assets."""

from __future__ import annotations

import json
import math
from typing import Any

from .lexicon_compiler import CompileError, _lua_string
from .dialogue_contract import DIALOGUE_LUA_CHUNK_MAX_CHARS
from .catalog_naming import ModuleNameRegistry, module_path, pascal_segment

def _lua_value(value: Any, indent: int = 0) -> str:
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return _lua_string(value)
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise CompileError("cannot render non-finite dialogue number")
        return format(value, ".15g")
    if isinstance(value, list):
        if not value:
            return "{}"
        lines = ["{"]
        for item in value:
            lines.append(" " * (indent + 4) + _lua_value(item, indent + 4) + ",")
        lines.append(" " * indent + "}")
        return "\n".join(lines)
    if isinstance(value, dict):
        if not value:
            return "{}"
        lines = ["{"]
        for key in sorted(value):
            lines.append(
                " " * (indent + 4)
                + f"[{_lua_string(str(key))}] = "
                + _lua_value(value[key], indent + 4)
                + ","
            )
        lines.append(" " * indent + "}")
        return "\n".join(lines)
    raise CompileError(f"cannot render dialogue value of type {type(value).__name__}")


def _render_dialogue_chunk(
    kind: str,
    label: str,
    records: list[dict[str, Any]],
) -> str:
    lines = [
        "-- Generated by tools/semantic_harness/codebuilder/build.py; do not edit by hand.",
        f"-- Dialogue {label} catalog; keep this file data-only.",
        "return {",
    ]
    for record in records:
        rendered = _lua_value(record, 4)
        lines.append("    " + rendered.replace("\n", "\n    ") + ",")
    lines.extend(["}", ""])
    return "\n".join(lines)


def _split_dialogue_records(
    kind: str,
    label: str,
    records: list[dict[str, Any]],
    max_chars: int = DIALOGUE_LUA_CHUNK_MAX_CHARS,
) -> list[str]:
    shards: list[str] = []
    current: list[dict[str, Any]] = []
    for record in records:
        candidate = current + [record]
        rendered = _render_dialogue_chunk(kind, label, candidate)
        if current and len(rendered) > max_chars:
            shards.append(_render_dialogue_chunk(kind, label, current))
            current = [record]
        else:
            current = candidate
    if current or not shards:
        shards.append(_render_dialogue_chunk(kind, label, current))
    if any(len(shard) > max_chars for shard in shards):
        raise CompileError(
            f"dialogue {kind} shard exceeds the {max_chars}-character output budget")
    return shards


def _dialogue_group(kind: str, record: dict[str, Any]) -> tuple[str, list[str]]:
    """Return a stable logical group and readable path segments for a record."""
    identifier = str(record.get("id", "catalog.unknown"))
    parts = identifier.split(".")
    if kind == "patterns":
        if len(parts) >= 3 and parts[1] == "dataset":
            if parts[2] in {"question", "clarify", "promise", "massive", "sgd"} and len(parts) >= 4:
                group_parts = parts[2:4]
            else:
                group_parts = parts[2:3]
        elif len(parts) >= 4:
            group_parts = parts[2:4]
        else:
            group_parts = parts[-2:]
        return ".".join(parts[: 2 + len(group_parts)]), group_parts

    response_parts = parts[1:] if parts and parts[0] == "semantic" else parts
    if len(response_parts) > 1:
        response_parts = [response_parts[0], "_".join(response_parts[1:])]
    return identifier, response_parts or ["Catalog"]


def render_dialogue_lua_plan(
    compiled: dict[str, Any],
    module_prefix: str,
    max_chars: int = DIALOGUE_LUA_CHUNK_MAX_CHARS,
) -> tuple[list[tuple[str, str]], dict[str, Any]]:
    """Plan readable, deterministic dialogue modules and their logical index."""
    rendered: list[tuple[str, str]] = []
    manifest: dict[str, Any] = {
        "catalogVersion": 2,
        "source": compiled["source"],
        "patterns": [],
        "responsePools": [],
    }
    registry = ModuleNameRegistry()
    for kind, key in (("patterns", "patterns"), ("responses", "responsePools")):
        groups: dict[str, tuple[list[str], list[dict[str, Any]]]] = {}
        for record in compiled[key]:
            canonical_id, segments = _dialogue_group(kind, record)
            if canonical_id not in groups:
                groups[canonical_id] = (segments, [])
            groups[canonical_id][1].append(record)
        parent = module_prefix + ("/Patterns" if kind == "patterns" else "/Responses")
        manifest_key = "patterns" if kind == "patterns" else "responsePools"
        for canonical_id, (segments, records) in groups.items():
            label = "/".join(pascal_segment(segment) for segment in segments)
            shards = _split_dialogue_records(kind, label, records, max_chars)
            modules: list[str] = []
            for index, shard in enumerate(shards, 1):
                shard_segments = list(segments)
                if len(shards) > 1:
                    shard_segments[-1] = f"{shard_segments[-1]}_Part{index:02d}"
                module = module_path(parent, shard_segments, f"{canonical_id}:{index}", registry)
                rendered.append((module, shard))
                modules.append(module)
            manifest[manifest_key].append({
                "id": canonical_id,
                "modules": modules,
                "recordCount": len(records),
            })
    return rendered, manifest


def render_dialogue_lua_shards(
    compiled: dict[str, Any],
    module_prefix: str,
    max_chars: int = DIALOGUE_LUA_CHUNK_MAX_CHARS,
) -> list[tuple[str, str]]:
    """Render deterministic data shards for the stable dialogue entry module."""
    return render_dialogue_lua_plan(compiled, module_prefix, max_chars)[0]


def render_dialogue_lua(
    compiled: dict[str, Any],
    pattern_modules: list[str] | None = None,
    response_modules: list[str] | None = None,
    module_manifest: dict[str, Any] | None = None,
    manifest_module: str | None = None,
) -> str:
    """Render the bounded interaction seed for the existing Lua registries.

    With no shard module lists this keeps the original standalone renderer for
    callers that use the compiler as a library. The build command supplies
    deterministic shard modules so the packaged entry file stays small.
    """
    if pattern_modules is None and response_modules is None:
        return "\n".join([
            "-- Generated by tools/semantic_harness/codebuilder/build.py; do not edit by hand.",
            "-- Exact Hoomans-authored interaction patterns and response variants.",
            "-- Referenced dialogue corpora provide coverage labels only; no turns are copied.",
            "return " + _lua_value(compiled),
            "",
        ])
    pattern_modules = pattern_modules or []
    response_modules = response_modules or []
    lines = [
        "-- Generated by tools/semantic_harness/codebuilder/build.py; do not edit by hand.",
        "-- Stable entry point for deterministic dialogue data shards.",
    ]
    if manifest_module is not None:
        lines.extend([
            f'local manifest = require "{manifest_module}"',
            "local result = {",
            "    [\"source\"] = manifest[\"source\"],",
            "    [\"catalogVersion\"] = manifest[\"catalogVersion\"],",
            "    [\"modules\"] = manifest[\"modules\"],",
        ])
    else:
        lines.extend([
            "local result = {",
            "    [\"source\"] = " + _lua_value(compiled["source"], 4) + ",",
            "    [\"catalogVersion\"] = 2,",
        ])
        if module_manifest is not None:
            lines.append("    [\"modules\"] = " + _lua_value(module_manifest, 4) + ",")
        lines.extend([
            "    [\"patterns\"] = {},",
            "    [\"responsePools\"] = {},",
            "}",
            "local function append(target, shard)",
            "    for index = 1, #shard do",
            "        target[#target + 1] = shard[index]",
            "    end",
            "end",
        ])
    if manifest_module is not None:
        lines.extend([
            "    [\"patterns\"] = {},",
            "    [\"responsePools\"] = {},",
            "}",
            "local function append(target, shard)",
            "    for index = 1, #shard do",
            "        target[#target + 1] = shard[index]",
            "    end",
            "end",
        ])
    for module in pattern_modules:
        lines.append(
            f'append(result["patterns"], require "{module}")')
    for module in response_modules:
        lines.append(
            f'append(result["responsePools"], require "{module}")')
    lines.extend(["return result", ""])
    return "\n".join(lines)


def render_dialogue_manifest(manifest: dict[str, Any]) -> str:
    """Render the human-readable logical module index beside a catalog hub."""
    return "\n".join([
        "-- Generated by tools/semantic_harness/codebuilder/build.py; do not edit by hand.",
        "-- Logical index for one deterministic dialogue catalog.",
        "return " + _lua_value(manifest),
        "",
    ])


def render_dialogue_translation(compiled: dict[str, Any], language: str) -> str:
    """Render the small localized shard emitted beside generated dialogue Lua."""
    if language not in ("EN", "TL"):
        raise CompileError(f"unsupported dialogue translation language {language}")
    translations = compiled.get("translations", {})
    values = translations.get(language, {})
    if not isinstance(values, dict):
        raise CompileError(f"dialogue translations for {language} must be an object")
    return json.dumps(
        {key: values[key] for key in sorted(values)},
        ensure_ascii=False,
        separators=(",", ":"),
    ) + "\n"
