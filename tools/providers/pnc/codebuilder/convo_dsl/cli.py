"""CLI for compiling modular language-pack .convo scripts into generated Lua."""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

from .emitter import emit_lua
from .parser import ConvoScript, parse_convo_file, validate_language_pack

REPO_ROOT = Path(__file__).resolve().parents[5]
SCRIPTS_DIR = REPO_ROOT / "Contents/mods/ProjectHoomans/common/media/translation"
LUA_OUT_DIR = (
    REPO_ROOT
    / "Contents/mods/ProjectHoomans/42.20/media/lua/shared/PNC/ConvoEngine/ResponseCatalog/Generated"
)


def _module_name(stem: str) -> str:
    return "".join(part.capitalize() for part in stem.replace("-", "_").split("_") if part)


def _discover_scripts(scripts_dir: Path) -> list[Path]:
    # Discover <LANG>/ConvoBlocks/**/*.convo as well as direct *.convo packs.
    found = list(scripts_dir.glob("*/ConvoBlocks/**/*.convo")) + list(scripts_dir.glob("*.convo"))
    return sorted(set(found))


def compile_all(
    scripts_dir: Path = SCRIPTS_DIR,
    lua_out_dir: Path = LUA_OUT_DIR,
    check_only: bool = False,
) -> list[str]:
    paths = _discover_scripts(scripts_dir)
    by_lang: dict[str, list[tuple[Path, ConvoScript]]] = {}
    for path in paths:
        script = parse_convo_file(path)
        by_lang.setdefault(script.language, []).append((path, script))

    for lang, items in by_lang.items():
        validate_language_pack([s for _, s in items])

    if check_only:
        return [str(p) for p in paths]

    lua_out_dir.mkdir(parents=True, exist_ok=True)
    written: list[str] = []
    module_names: list[str] = []

    # Emit lexicons first so generated pools can assume lex tables are already loaded
    ordered: list[tuple[Path, ConvoScript]] = []
    for lang in sorted(by_lang.keys()):
        items = by_lang[lang]
        lex_only = [(p, s) for p, s in items if s.lexicons and not s.pools]
        rest = [(p, s) for p, s in items if not (s.lexicons and not s.pools)]
        ordered.extend(lex_only + rest)

    for path, script in ordered:
        mod = _module_name(path.stem)
        module_names.append(mod)
        rel = str(path.relative_to(REPO_ROOT)) if path.is_relative_to(REPO_ROOT) else path.name

        lua_path = lua_out_dir / f"{mod}.lua"
        lua_path.write_text(emit_lua(script, rel), encoding="utf-8")
        written.append(str(lua_path))

    init_lines = [
        "-- Generated by ConvoDSL; do not edit by hand.",
        "PNC = PNC or {}",
        "PNC.ConvoEngine = PNC.ConvoEngine or {}",
        "",
    ]
    for mod in module_names:
        init_lines.append(f'require "PNC/ConvoEngine/ResponseCatalog/Generated/{mod}"')
    init_lines.extend(["", "return true", ""])

    init_path = lua_out_dir / "Init.lua"
    init_path.write_text("\n".join(init_lines), encoding="utf-8")
    written.append(str(init_path))
    return written


def _run_preview(pool_id: str, count: int) -> int:
    lua_code = f"""
local T = require "tests/support/test"
T.addPackagePaths()
local Catalog = require "PNC/ConvoEngine/Dialogue/ResponseCatalog"
local Lexicon = require "PNC/ConvoEngine/Lexicon"
require "PNC/ConvoEngine/ResponseCatalog/Generated/Init"
local pool = Catalog.Get({pool_id!r})
if not pool then
    io.stderr:write("Pool not found: " .. {pool_id!r} .. "\\n")
    os.exit(1)
end
local styles = {{ "supportive", "shaken", "brave", "aggressive", "tactical", "cold" }}
for i = 1, {count} do
    local v = pool.variants[((i - 1) % #pool.variants) + 1]
    local ctx = {{
        npcID = "preview_npc",
        speakerStyle = styles[((i - 1) % #styles) + 1],
        isNightOrDusk = (i % 2 == 0),
        raining = (i % 3 == 0),
    }}
    local text = Lexicon.Expand(v.fallback, ctx, {{ ["speaker.name"] = "Elena", ["addressee.name"] = "Pat", ["claimed.name"] = "Myrna" }}, {{ salt = "p:" .. i }})
    print(string.format("[%d | %s | night=%s] %s", i, ctx.speakerStyle, tostring(ctx.isNightOrDusk), text))
end
"""
    proc = subprocess.run(["lua", "-e", lua_code], cwd=str(REPO_ROOT), check=False)
    return proc.returncode


def _run_test_input(raw_text: str) -> int:
    lua_code = f"""
local T = require "tests/support/test"
T.addPackagePaths()
local Normalizer = require "PsychopatzCore/Semantics/PsychopatzSemanticNormalizer"
local n = Normalizer.Normalize({raw_text!r})
print("raw:        " .. tostring(n.rawText))
print("normalized: " .. tostring(n.normalizedText))
print("lemmas:     " .. table.concat(n.lemmas or {{}}, " "))
print("clean:      " .. table.concat(n.cleanTokens or {{}}, " "))
print("tone:       " .. tostring(n.playerTone) .. " (question=" .. tostring(n.isQuestion) .. ", bang=" .. tostring(n.isExclamation) .. ")")
"""
    proc = subprocess.run(["lua", "-e", lua_code], cwd=str(REPO_ROOT), check=False)
    return proc.returncode


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Compile, preview, or test .convo dialogue language packs.")
    parser.add_argument("--check", action="store_true", help="Validate scripts without writing output.")
    parser.add_argument("--preview", metavar="POOL_ID", help="Print sample dynamically expanded lines for a pool.")
    parser.add_argument("--count", type=int, default=8, help="Number of lines for --preview (default 8).")
    parser.add_argument("--test-input", metavar="TEXT", help="Inspect English NLP normalization & tone for raw player text.")
    args = parser.parse_args(argv)
    if args.preview:
        return _run_preview(args.preview, max(1, args.count))
    if args.test_input:
        return _run_test_input(args.test_input)
    try:
        results = compile_all(check_only=args.check)
    except ValueError as exc:
        print(f"ConvoDSL error: {exc}", file=sys.stderr)
        return 1
    mode = "validated" if args.check else "compiled"
    print(f"ConvoDSL {mode} {len(results)} artifact(s).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
