"""Deterministic Lua emitter for modular language-pack .convo scripts."""

from __future__ import annotations

from typing import Any

from .parser import ConvoScript, LexNode, OfferNode, PoolNode, VariantNode


def _lua_escape(text: str) -> str:
    return (
        text.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
    )


def _lua_scalar(val: Any) -> str:
    if isinstance(val, list):
        return "{ " + ", ".join(_lua_scalar(item) for item in val) + " }"
    if isinstance(val, bool):
        return "true" if val else "false"
    if isinstance(val, (int, float)):
        return str(val)
    return f'"{_lua_escape(str(val))}"'


def _lua_when(when: dict[str, Any]) -> str:
    if not when:
        return "nil"
    parts = [f"{k} = {_lua_scalar(when[k])}" for k in sorted(when.keys())]
    return "{ " + ", ".join(parts) + " }"


def _template_id(namespace: str, pool: PoolNode, variant: VariantNode) -> str:
    clean_pool = pool.pool_id
    if clean_pool.startswith("semantic."):
        clean_pool = clean_pool[len("semantic.") :]
    return f"{namespace}.{clean_pool}.{variant.variant_id}"


def _variant_id(pool: PoolNode, variant: VariantNode) -> str:
    return f"{pool.pool_id}.{variant.variant_id}"


def emit_lua(script: ConvoScript, source_rel: str) -> str:
    lines: list[str] = [
        f"-- Generated by ConvoDSL ({script.language}) from {source_rel}; do not edit by hand.",
        "PNC = PNC or {}",
        "PNC.Semantics = PNC.Semantics or {}",
        "PNC.ConvoEngine = PNC.ConvoEngine or {}",
        "",
    ]

    if script.lexicons:
        lines.extend([
            "local Lexicon = PNC.ConvoEngine.Lexicon or require \"PNC/ConvoEngine/Lexicon\"",
            "",
        ])
        for lx in script.lexicons:
            lines.extend(_emit_lex_lua(script.language, lx))

    if script.blueprints:
        lines.extend([
            "PNC.ConvoEngine.OfferBlueprints = PNC.ConvoEngine.OfferBlueprints or {}",
            "",
        ])
        for bp in script.blueprints:
            lines.append(f'PNC.ConvoEngine.OfferBlueprints["{_lua_escape(bp.blueprint_id)}"] = {{')
            for offer in bp.offers:
                lines.extend(_emit_offer_lua(offer))
            lines.append("}")
            lines.append("")

    if script.pools:
        lines.extend([
            "local Catalog = PNC.ConvoEngine.ResponseCatalog",
            'if type(Catalog) ~= "table" or type(Catalog.Register) ~= "function" then',
            "    return false",
            "end",
            "",
            "PNC.ConvoEngine.GeneratedOffers = PNC.ConvoEngine.GeneratedOffers or {}",
            "PNC.ConvoEngine.GeneratedOfferUses = PNC.ConvoEngine.GeneratedOfferUses or {}",
            "",
            "local function v(id, tid, fallback, when, priority, hasTokens, plan)",
            "    return {",
            "        id = id,",
            "        templateID = tid,",
            "        fallback = fallback,",
            "        when = when,",
            "        priority = priority or 6,",
            "        hasTokens = hasTokens == true,",
            "        plan = plan,",
            "    }",
            "end",
            "",
        ])

        bp_map = {bp.blueprint_id: bp.offers for bp in script.blueprints}
        for pool in script.pools:
            effective_offers = list(pool.offers)
            for use_id in pool.uses:
                effective_offers.extend(bp_map.get(use_id, []))
            pool_offers_var = None
            if effective_offers:
                pool_offers_var = "_po"
                lines.append("local _po = {")
                for offer in effective_offers:
                    frame_parts = [f'intent = "{_lua_escape(offer.intent)}"', f'speechAct = "{_lua_escape(offer.intent)}"']
                    if offer.action:
                        frame_parts.append(f'action = "{_lua_escape(offer.action)}"')
                        frame_parts.append('target = "SELF"')
                    elif offer.subject:
                        frame_parts.append(f'subject = "{_lua_escape(offer.subject)}"')
                    lines.append(
                        f'    {{ id = "{_lua_escape(offer.offer_id)}", '
                        f'labelKey = "{_lua_escape(offer.offer_id)}.label", labelFallback = "{_lua_escape(offer.label)}", '
                        f'utteranceKey = "{_lua_escape(offer.offer_id)}.say", utteranceFallback = "{_lua_escape(offer.say)}", '
                        f'frame = {{ ' + ", ".join(frame_parts) + " } },"
                    )
                lines.append("}")
            lines.append(f'Catalog.Register("{_lua_escape(pool.pool_id)}", {{')
            lines.append("    variants = {")
            for var in pool.variants:
                vid = _variant_id(pool, var)
                tid = _template_id(script.namespace, pool, var)
                if " >> " in var.fallback:
                    parts = [p.strip() for p in var.fallback.split(" >> ") if p.strip()]
                    first_fb = parts[0]
                    has_toks = "true" if any("{" in p for p in parts) else "false"
                    turn_rows = []
                    for idx, part in enumerate(parts):
                        cont = "continue" if idx < len(parts) - 1 else "await_player"
                        seg_tid = tid if idx == 0 else f"{tid}.t{idx + 1}"
                        off_str = f", offers = {pool_offers_var}" if (pool_offers_var and idx == len(parts) - 1) else ""
                        turn_rows.append(
                            f'{{ id = "t{idx + 1}", continuation = "{cont}", segments = {{ {{ kind = "translation", templateID = "{_lua_escape(seg_tid)}", fallback = "{_lua_escape(part)}" }} }}{off_str} }}'
                        )
                    plan_lua = f'{{ sourcePoolID = "{_lua_escape(pool.pool_id)}", turns = {{ ' + ", ".join(turn_rows) + " } }"
                    lines.append(
                        f'        v("{_lua_escape(vid)}", "{_lua_escape(tid)}", '
                        f'"{_lua_escape(first_fb)}", {_lua_when(var.when)}, {var.priority}, {has_toks}, {plan_lua}),'
                    )
                else:
                    has_toks = "true" if "{" in var.fallback else "false"
                    if pool_offers_var:
                        plan_lua = (
                            f'{{ sourcePoolID = "{_lua_escape(pool.pool_id)}", turns = {{ {{ '
                            f'segments = {{ {{ kind = "translation", templateID = "{_lua_escape(tid)}", fallback = "{_lua_escape(var.fallback)}" }} }}, '
                            f'offers = {pool_offers_var} }} }} }}'
                        )
                        lines.append(
                            f'        v("{_lua_escape(vid)}", "{_lua_escape(tid)}", '
                            f'"{_lua_escape(var.fallback)}", {_lua_when(var.when)}, {var.priority}, {has_toks}, {plan_lua}),'
                        )
                    else:
                        lines.append(
                            f'        v("{_lua_escape(vid)}", "{_lua_escape(tid)}", '
                            f'"{_lua_escape(var.fallback)}", {_lua_when(var.when)}, {var.priority}, {has_toks}),'
                        )
            lines.append("    },")
            lines.append("})")
            lines.append("")

            if pool.offers:
                lines.append(f'PNC.ConvoEngine.GeneratedOffers["{_lua_escape(pool.pool_id)}"] = {{')
                for offer in pool.offers:
                    lines.extend(_emit_offer_lua(offer))
                lines.append("}")
                lines.append("")
            if pool.uses:
                uses_lua = ", ".join(f'"{_lua_escape(u)}"' for u in pool.uses)
                lines.append(
                    f'PNC.ConvoEngine.GeneratedOfferUses["{_lua_escape(pool.pool_id)}"] = {{ {uses_lua} }}'
                )
                lines.append("")

    lines.append("return true")
    lines.append("")
    return "\n".join(lines)


def _emit_lex_lua(lang: str, lx: LexNode) -> list[str]:
    out = [f'Lexicon.Register("{_lua_escape(lang)}", "{_lua_escape(lx.lex_id)}", {{']
    for entry in lx.entries:
        words_lua = ", ".join(f'"{_lua_escape(w)}"' for w in entry.words)
        out.append(
            f"    {{ when = {_lua_when(entry.when)}, priority = {entry.priority}, words = {{ {words_lua} }} }},"
        )
    out.append("})")
    out.append("")
    return out


def _emit_offer_lua(offer: OfferNode) -> list[str]:
    out = [
        "    {",
        f'        id = "{_lua_escape(offer.offer_id)}",',
        f'        label = "{_lua_escape(offer.label)}",',
        f'        say = "{_lua_escape(offer.say)}",',
        f'        intent = "{_lua_escape(offer.intent)}",',
        f'        subject = "{_lua_escape(offer.subject)}",',
    ]
    if offer.claim is not None:
        out.append(f'        claim = "{_lua_escape(offer.claim)}",')
    if offer.style is not None:
        out.append(f'        style = "{_lua_escape(offer.style)}",')
    if offer.utility is not None:
        out.append(f'        utility = "{_lua_escape(offer.utility)}",')
    if offer.when:
        out.append(f"        when = {_lua_when(offer.when)},")
    out.append("    },")
    return out
