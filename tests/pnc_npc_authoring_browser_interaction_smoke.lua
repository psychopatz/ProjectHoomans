local T = require 'tests/support/test'
local F = require('tests/support/pnc_authoring_ui')()
T.load('ProjectHoomans', 'client', 'PNC/UI/NPCAuthoring/PNC_NPCAuthoringCatalog.lua')
local e = F.Class:new(0, 0, 1060, 620, { mode = 'debug', uiScale = 1 })
e:initialise(); e:instantiate()
local browser, applied = e.itemExplorer
local items = { { id = 'A', label = 'Alpha', search = 'alpha' }, { id = 'B', label = 'Beta', search = 'beta' } }
browser:Show({ mode = 'outfit', items = items, onChoose = function(item) applied = item.id; return true end })
T.falsy(browser.quantity.visible, 'outfits do not expose item quantity')
T.falsy(browser.destination.visible, 'outfits do not expose bag destinations')
T.falsy(browser.compatible, 'the compatibility bypass control is absent')
T.equal(browser.confirm.title, 'Apply outfit', 'outfits have a contextual apply action')
T.falsy(browser.confirm.enabled, 'an explicit selection is required')
browser.tiles[1].onclick(browser, browser.tiles[1])
T.equal(browser.selectedID, 'A', 'native-style target/button callback selects the stable ID')
T.truthy(browser.confirm.enabled, 'the reviewed selection is actionable')
T.equal(browser.tiles[1].backgroundColor.g, .32, 'selection is visibly highlighted')
browser.search:setText('beta')
T.equal(browser.visibleRows[1].id, 'B', 'filtering changes the visible result')
T.falsy(browser.selectedID, 'a filtered-out selection is cleared')
T.falsy(browser.confirm.enabled, 'a filtered-out item cannot be applied')
browser.confirm.onclick(browser)
T.falsy(applied, 'a stale callback cannot apply the hidden item')
browser.tiles[1].onclick(browser, browser.tiles[1]); browser.confirm.onclick(browser)
T.equal(applied, 'B', 'only the explicitly selected visible result is applied')
T.falsy(browser.visible, 'successful Apply dismisses the browser')
for _, mode in ipairs({ 'preset', 'choice', 'worn', 'held', 'attach', 'carry' }) do
    browser:Show({ mode = mode, items = items, onChoose = function() return true end })
    T.equal(browser.quantity.visible, mode == 'carry', 'quantity is contextual to carried inventory')
    T.equal(browser.destination.visible, mode == 'carry', 'destination is contextual to carried inventory')
    browser:Hide()
end
browser:Show({ mode = 'outfit', items = items, onChoose = function() return false, 'rejected' end })
browser.tiles[1].onclick(browser, browser.tiles[1]); browser.confirm.onclick(browser)
T.truthy(browser.visible, 'rejection retains the editable selection')
T.equal(browser.hintText, 'rejected', 'the apply failure is explained')
browser.search:setText('missing')
T.equal(browser.total, 0, 'empty filters have no results')
T.equal(browser.hintText, 'No matching results', 'empty state is explicit')
T.equal(browser.counter.name, '0-0 / 0', 'pagination uses a supported ASCII range')
T.finish('pnc_npc_authoring_browser_interaction_smoke')
